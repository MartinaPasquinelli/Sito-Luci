(function () {
    const calendarContainer = document.getElementById('calendar-container');
    if (!calendarContainer) return;

    let currentDate = new Date();
    currentDate.setDate(1);

    function renderCalendar(date) {
        const year = date.getFullYear();
        const month = date.getMonth();

        const monthNames = [
            "January",
            "February",
            "March",
            "April",
            "May",
            "June",
            "July",
            "August",
            "September",
            "October",
            "November",
            "December"
        ];

        // Giorno della settimana del primo giorno del mese
        const firstDay = new Date(year, month, 1).getDay();

        // Numero di giorni nel mese
        const daysInMonth = new Date(year, month + 1, 0).getDate();

        // Data di oggi
        const today = new Date();

        let html = `
            <div style="
                display:flex;
                justify-content:space-between;
                align-items:center;
                margin-bottom:5px;
            ">
                <button
                    id="prev-month"
                    style="
                        background:none;
                        border:none;
                        font-size:16px;
                    "
                >&lt;</button>

                <span class="pink-text">
                    ${monthNames[month]} ${year}
                </span>

                <button
                    id="next-month"
                    style="
                        background:none;
                        border:none;
                        font-size:16px;
                    "
                >&gt;</button>
            </div>

            <table class="calendar-table">
                <tr>
                    <th>S</th>
                    <th>M</th>
                    <th>T</th>
                    <th>W</th>
                    <th>T</th>
                    <th>F</th>
                    <th>S</th>
                </tr>
                <tr>
        `;

        let dayCount = 1;

        // 42 celle = 6 settimane
        for (let i = 0; i < 42; i++) {

            // Celle vuote prima dell'inizio del mese
            if (i < firstDay || dayCount > daysInMonth) {
                html += `<td></td>`;

            } else {

                // OGGI
                const isToday =
                    year === today.getFullYear() &&
                    month === today.getMonth() &&
                    dayCount === today.getDate();

                // D-DAY: 25 Novembre 2026
                const isDDay =
                    year === 2026 &&
                    month === 10 &&
                    dayCount === 25;

                let classes = 'class="pink-text"';
                let content = dayCount;

                // Il D-Day ha la precedenza visiva
                if (isDDay) {
                    classes = 'class="pink-text d-day"';

                    content = `
                        <span class="d-day-number" title="D-Day!!!">
                            ${dayCount}
                        </span>
                        <span class="d-day-label">
                            D-DAY!!!
                        </span>
                    `;


                } else if (isToday) {
                    classes = 'class="current-day"';
                }

                html += `
                    <td ${classes}>
                        ${content}
                    </td>
                `;

                dayCount++;
            }

            // Nuova riga ogni 7 giorni
            if ((i + 1) % 7 === 0) {
                html += `</tr><tr>`;
            }
        }

        html += `
                </tr>
            </table>
        `;

        calendarContainer.innerHTML = html;

        // Mese precedente
        document
            .getElementById('prev-month')
            .addEventListener('click', () => {
                renderCalendar(new Date(year, month - 1, 1));
            });

        // Mese successivo
        document
            .getElementById('next-month')
            .addEventListener('click', () => {
                renderCalendar(new Date(year, month + 1, 1));
            });
    }

    renderCalendar(currentDate);
})();

